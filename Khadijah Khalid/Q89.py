# Build a program that demonstrates all four basic data types covered in the lecture and verifies each with `type()`.

# Integer
age = 25
print("Age (Integer):", age, "Type:", type(age))

# Float
height = 5.6
print("Height (Float):", height, "Type:", type(height))

# String
name = "Katty"
print("Name (String):", name, "Type:", type(name))

# Boolean
is_student = True
print("Is Student (Boolean):", is_student, "Type:", type(is_student))