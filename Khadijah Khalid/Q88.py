#  Create a product price as a string, convert it to float, convert that float to integer, and show the type after each step.

product_price_str = "19.99"
print("Product Price (String):", product_price_str, "Type:", type(product_price_str))

product_price_float = float(product_price_str)
print("Product Price (Float):", product_price_float, "Type:", type(product_price_float))

product_price_int = int(product_price_float)
print("Product Price (Integer):", product_price_int, "Type:", type(product_price_int))

                                                                   