#Q87. Create a student age as a string, convert it to integer, then create a float representation of the age. Print all stages.

student_age_str = "20"
student_age_int = int(student_age_str)
student_age_float = float(student_age_int)

print("Student age string:",student_age_str)
print("Student age integer:",student_age_int)
print("Student age float:",student_age_float)
