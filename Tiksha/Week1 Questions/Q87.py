# Create a student age as a string, convert it to integer, then create a float representation of the age. Print all stages.

student_age_str = "20"              # str

# Convert student_age_str to int
student_age_int = int(student_age_str)  # int

# Convert student_age_int to float
student_age_float = float(student_age_int)  # float

print("\nStudent Age (String):", student_age_str, "\nType of student_age_str:", type(student_age_str))
print("\nStudent Age (Integer):", student_age_int, "\nType of student_age_int:", type(student_age_int))
print("\nStudent Age (Float):", student_age_float, "\nType of student_age_float:", type(student_age_float)) 