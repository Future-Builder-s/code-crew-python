# Q45: Practice Question 45
# Build a short program that demonstrates Python's dynamic typing using one variable.

var = "Hola, nice to meet you!"
print("\nValue of var:", var, "\nType of var:", type(var))

var = 96
print("\nValue of var:", var, "\nType of var:", type(var))

var = 96.0
print("\nValue of var:", var, "\nType of var:", type(var))

var = "96"
print("\nValue of var:", var, "\nType of var:", type(var))
