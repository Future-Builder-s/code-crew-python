# Integer
age = 18
print("\nAge (Integer):", age, "Type:", type(age))

# Float
height = 8.6
print("\nHeight (Float):", height, "Type:", type(height))

# String
name = "Katherine"
print("\nName (String):", name, "Type:", type(name))

# Boolean
is_student = True
print("\nIs_Student (Boolean):", is_student, "Type:", type(is_student))

# Conversions
age_as_float = float(age)
print("\nAge as Float:", age_as_float, "Type:", type(age_as_float))

height_as_int = int(height)
print("\nHeight as Integer:", height_as_int, "Type:", type(height_as_int))

name_as_list = list(name)
print("\nName as List:", name_as_list, "Type:", type(name_as_list))