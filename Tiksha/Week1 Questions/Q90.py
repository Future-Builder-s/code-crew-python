# Q90: Practice Question 90
# Build a dynamic-typing demonstration where one variable changes through at least four different basic types. Print value and type each time.

# Start with an integer
dynamic_var = 10
print("\nDynamic Variable (Integer):", dynamic_var, "\nType of dynamic_var:", type(dynamic_var))

# Change to float
dynamic_var = 10.5
print("\nDynamic Variable (Float):", dynamic_var, "\nType of dynamic_var:", type(dynamic_var))

# Change to string
dynamic_var = "Now I'm a string"
print("\nDynamic Variable (String):", dynamic_var, "\nType of dynamic_var:", type(dynamic_var))

# Change to boolean
dynamic_var = True
print("\nDynamic Variable (Boolean):", dynamic_var, "\nType of dynamic_var:", type(dynamic_var))