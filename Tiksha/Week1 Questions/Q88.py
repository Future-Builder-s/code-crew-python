# Create a product price as a string, convert it to float, convert that float to integer, and show the type after each step.

product_price_str = "199.99"         # str

# Convert product_price_str to float
product_price_float = float(product_price_str)  # float

# Convert product_price_float to int
product_price_int = int(product_price_float)  # int

print("\nProduct Price (String):", product_price_str, "\nType of product_price_str:", type(product_price_str))
print("\nProduct Price (Float):", product_price_float, "\nType of product_price_float:", type(product_price_float))
print("\nProduct Price (Integer):", product_price_int, "\nType of product_price_int:", type(product_price_int))