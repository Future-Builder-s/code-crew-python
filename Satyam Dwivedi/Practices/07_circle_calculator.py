# Circle Calculator
# Input for radius
radius = float(input("Enter radius: "))
pi = 3.14
# Calculate area of circle
a_f_c = pi*(radius**2)
# print area of circle 
print(f"The Area of circle is: {a_f_c}")
# Calculate Circumference of circle
c_f_c = 2*(pi*radius)
# print Circumference of circle 
print(f"The Circumference of circle is: {c_f_c}")
