#Basic Calculator for Addition , Subtraction, Multiplication and Division
first_number = int(input("Enter First Number: "))
second_number = int(input("Enter Second Number: "))

Add = first_number + second_number
Sub = first_number - second_number
Mult = first_number * second_number
Div = first_number / second_number
print(f"The Addition of {first_number} and {second_number} = {Add} \nThe Subtraction of {first_number} and {second_number} = {Sub} \nThe Multiplication of {first_number} and {second_number} = {Mult} \nThe Division of {first_number} and {second_number} = {Div}")