# Average calculator of three numbers
# Intput for calculat average
no1st = int(input("Enter first number: "))
no2nd = int(input("Enter second number: "))
no3rd = int(input("Enter third number: "))

# Sum of all three numbers 
sum = no1st+no2nd+no3rd
# Average of all three numbers
avg = sum/3
# Print Average
print(f"Average: {avg}")